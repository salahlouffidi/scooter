// Embeds the two UI fonts (SIL OFL 1.1) as base64 @font-face rules so the game stays fully
// offline and never depends on file:// font loading inside the Android WebView.
//   npm run build:fonts
const fs = require('fs'), path = require('path');
const pkg = (name, file) => fs.readFileSync(path.join(__dirname, '..', 'node_modules', '@fontsource', name, 'files', file));
const faces = [
  ['Lilita One', 400, pkg('lilita-one', 'lilita-one-latin-400-normal.woff2')],
  ['Nunito', 700, pkg('nunito', 'nunito-latin-700-normal.woff2')],
  ['Nunito', 800, pkg('nunito', 'nunito-latin-800-normal.woff2')],
  ['Nunito', 900, pkg('nunito', 'nunito-latin-900-normal.woff2')]
];
let css = '/* Generated by tools/build-fonts.cjs — Lilita One & Nunito, SIL Open Font License 1.1. Do not edit. */\n';
for (const [family, weight, data] of faces) {
  css += `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${data.toString('base64')}) format('woff2');}\n`;
}
const out = path.join(__dirname, '../app/src/main/assets/game/css/fonts.css');
fs.writeFileSync(out, css);
console.log('wrote', path.relative(process.cwd(), out), (css.length / 1024).toFixed(1) + ' KB');
